namespace Inventory
{
	// "Использовать" предмет из инвентаря (двойной клик, пункт меню): кто-то на игроке, кто умеет применять предметы
	// своего вида. Например, Player.PlayerHealing — аптечки, позже — еда, батарейки и т.п. Инвентарь сам не знает,
	// что значит "использовать" — он спрашивает всех таких обработчиков на игроке (InventoryHolder.TryUse).
	public interface IItemUseHandler
	{
		// можно ли вообще использовать этот предмет (для пункта меню). Не проверяет "прямо сейчас" — для этого TryUse
		bool CanUse(ItemInstance item);
		// начать использование. false — сейчас нельзя (руки заняты, уже лечится и т.п.)
		bool TryUse(ItemInstance item);
	}
}
