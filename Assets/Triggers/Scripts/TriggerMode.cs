namespace Triggers
{
	// Режим срабатывания BaseTrigger — что происходит с детектором после первого успешного Enter
	public enum TriggerMode
	{
		// Срабатывает один раз за игру, затем сам отключает свой Collider — дальше не реагирует ни на что
		OneShot,
		// Может срабатывать снова и снова, но не чаще, чем раз в Cooldown секунд (0 — без ограничения)
		Repeatable
	}
}
