namespace Weapons
{
	// Реализуй на любом объекте (или его родителе — WeaponController ищет через GetComponentInParent),
	// который можно чинить оружием с MeleeWeaponData.Repair.CanRepair (например, кнопка-триггер). Отдельно от
	// IDamageable, потому что чинить и наносить урон — разные объекты и разная реакция на попадание.
	public interface IRepairable
	{
		void Repair(int amount);

		// Насколько объект починен: 0..1. Показывается в HUD круговым индикатором, пока его чинят
		// (см. HUD.RepairProgressUI). Отрицательное — прогресс неизвестен, индикатор не показывается;
		// так по умолчанию, поэтому реализациям без понятия "прочность" добавлять ничего не нужно
		float RepairProgress => -1f;
	}
}
