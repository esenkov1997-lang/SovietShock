using UnityEngine;

namespace Weapons
{
	// Повесь на объект (манекен, монстра, дерево и т.д.), для которого декаль при попадании должна
	// зависеть от самой цели, а не от оружия — например, кровь при попадании в манекен, вместо
	// стандартного пулевого отверстия из WeaponData. Если этого компонента нет — используется
	// декаль оружия (нормальное поведение для стен и прочего окружения).
	public class ImpactSurface : MonoBehaviour
	{
		[Tooltip("Декаль, которая заспавнится при попадании в этот объект, вместо декали из WeaponData")]
		public GameObject DecalPrefab;
		[Tooltip("Через сколько секунд декаль будет уничтожена. 0 или меньше — взять значение из WeaponData")]
		public float DecalLifetimeOverride = 0f;
	}
}
